"""Abstractions the use cases depend on. Frappe implementations live in
mcp_connector.infrastructure; tests use in-memory fakes."""

from typing import Any, Callable, Optional, Protocol, TypeVar

from mcp_connector.domain.audit import AuditEntry

from .dto import DoctypeInfo, ReportInfo

T = TypeVar("T")


class ErpGateway(Protocol):
	"""ERP operations, always executed as the calling user with Frappe permissions enforced.

	Implementations raise mcp_connector.domain.errors.ErpFailure for expected
	failures (permission, not_found, validation, conflict).
	"""

	def doctype_info(self, doctype: str) -> Optional[DoctypeInfo]: ...

	def has_permission(self, doctype: str, ptype: str, user: Optional[str] = None) -> bool: ...

	def list_documents(
		self, doctype: str, fields: list, filters: list, or_filters: list, order_by: str, start: int, limit: int
	) -> list: ...

	def count_documents(self, doctype: str, filters: list, or_filters: list) -> int: ...

	def list_names(self, doctype: str, filters: list, limit: int) -> list: ...

	def document_exists(self, doctype: str, name: str) -> bool: ...

	def document_matches(self, doctype: str, name: str, conditions: tuple) -> bool: ...

	def get_document(self, doctype: str, name: str) -> dict: ...

	def create_document(self, doctype: str, data: dict) -> dict: ...

	def update_document(self, doctype: str, name: str, data: dict) -> dict: ...

	def delete_document(self, doctype: str, name: str) -> None: ...

	def submit_document(self, doctype: str, name: str) -> dict: ...

	def cancel_document(self, doctype: str, name: str) -> dict: ...

	def workflow_actions(self, doctype: str, name: str) -> dict: ...

	def apply_workflow_action(self, doctype: str, name: str, action: str) -> dict: ...

	def report_info(self, report: str) -> Optional[ReportInfo]: ...

	def run_report(self, report: str, filters: dict, limit: int) -> dict: ...

	def call_method(self, method: str, arguments: dict) -> Any: ...

	def drain_messages(self) -> list: ...


class AuditSink(Protocol):
	def record(self, entry: AuditEntry) -> None: ...


class UnitOfWork(Protocol):
	def atomic(self, work: Callable[[], T]) -> T:
		"""Run work; undo its database writes if it raises, then re-raise."""
		...
